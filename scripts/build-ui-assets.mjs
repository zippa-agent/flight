import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const assetsDir = path.join(root, "ui", "dist", "assets");
const target = path.join(root, "src", "ui", "assets.ts");

const files = await readdir(assetsDir);
const jsFile = files.find((file) => file.endsWith(".js"));
const cssFile = files.find((file) => file.endsWith(".css"));

if (!jsFile || !cssFile) {
  throw new Error("UI build did not produce one JS asset and one CSS asset.");
}

const [js, css] = await Promise.all([
  readFile(path.join(assetsDir, jsFile), "utf8"),
  readFile(path.join(assetsDir, cssFile), "utf8"),
]);

await writeFile(target, [
  "// Generated by scripts/build-ui-assets.mjs. Edit files in ui/src instead.",
  `export const APP_CSS = ${JSON.stringify(css)};`,
  `export const APP_JS = ${JSON.stringify(js)};`,
  "",
].join("\n"));
